const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context={window:{},Intl,Date,TextEncoder,URL};
vm.runInNewContext(fs.readFileSync('meal-time.js','utf8'),context);
const t=context.window.EnkaiTime;
assert.equal(t.guessZone('São Paulo'),'America/Sao_Paulo');
assert.equal(t.guessZone('North York, Ontario'),'America/Toronto');
assert.equal(t.guessZone('London, Ontario'),'America/Toronto');
assert.equal(t.guessZone('London, UK'),'Europe/London');
assert.equal(t.toInstant('2026-12-24T12:00','America/Toronto'),'2026-12-24T17:00:00.000Z');
assert.equal(t.toInstant('2026-07-24T12:00','America/Toronto'),'2026-07-24T16:00:00.000Z');
assert.equal(t.toInstant('2026-12-24T12:00','America/Sao_Paulo'),'2026-12-24T15:00:00.000Z');
assert.equal(t.toInstant('2026-12-24T12:00','Asia/Kathmandu'),'2026-12-24T06:15:00.000Z');
assert.equal(t.toInstant('2026-12-31T23:30','Pacific/Honolulu'),'2027-01-01T09:30:00.000Z');
assert.throws(()=>t.toInstant('2026-03-08T02:30','America/Toronto'),/skipped/);
assert.throws(()=>t.toInstant('2026-11-01T01:30','America/Toronto'),/twice/);
assert.equal(t.toInstant('2026-11-01T01:30','America/Toronto','earlier'),'2026-11-01T05:30:00.000Z');
assert.equal(t.toInstant('2026-11-01T01:30','America/Toronto','later'),'2026-11-01T06:30:00.000Z');
assert.throws(()=>t.toInstant('2026-02-30T12:00','America/Toronto'),/valid/);
assert.throws(()=>t.toInstant('2026-12-24T12:00','Not/AZone'),/zone/);
assert.equal(t.candidates('2011-12-30T12:00','Pacific/Apia').length,0);
assert.throws(()=>t.toInstant('2026-10-04T02:15','Australia/Lord_Howe'),/skipped/);
assert.equal(t.candidates('2026-04-05T01:45','Australia/Lord_Howe').length,2);
const ics=t.calendar({id:'test',title:'Dinner, sushi; '+ '宴'.repeat(50)+'\nInjected: no',restaurant:'One',location:'Toronto',timeZone:'America/Toronto',status:'Unbooked',selectedTime:'2026-12-24T17:00:00.000Z',duration:90});
assert.ok(ics.includes('DTSTART:20261224T170000Z'));
assert.ok(ics.includes('DTEND:20261224T183000Z'));
assert.ok(ics.split('\r\n').every(line=>Buffer.byteLength(line)<=75));
assert.ok(!ics.includes('\r\nInjected:'));
console.log('Destination conversion, DST gaps and overlaps, non-hour offsets, and calendar output passed.');
